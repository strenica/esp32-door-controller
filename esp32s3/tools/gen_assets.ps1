# Regenerates vrata/src/generated/bootstrap_css.h from the site's Bootstrap CSS
# (the one copy at server/oss/assets/bootstrap.min.css, Bootstrap 4.5.2).
# The CSS is gzip-compressed (~160 KB -> ~24 KB) and served with
# "Content-Encoding: gzip". Only needed if the CSS is ever replaced.
#
#   powershell -ExecutionPolicy Bypass -File tools\gen_assets.ps1
#
# gen_assets.sh is the POSIX equivalent and produces the same header.

param(
  [string]$Css = (Join-Path $PSScriptRoot "..\..\server\oss\assets\bootstrap.min.css"),
  [string]$Out = (Join-Path $PSScriptRoot "..\vrata\src\generated\bootstrap_css.h")
)

$ErrorActionPreference = "Stop"
$bytes = [IO.File]::ReadAllBytes($Css)

$ms = New-Object IO.MemoryStream
$gz = New-Object IO.Compression.GZipStream($ms, [IO.Compression.CompressionLevel]::Optimal)
$gz.Write($bytes, 0, $bytes.Length)
$gz.Close()
$data = $ms.ToArray()

$sb = New-Object Text.StringBuilder
[void]$sb.AppendLine("// GENERATED by tools/gen_assets.sh (or .ps1) - do not edit.")
[void]$sb.AppendLine("// Source: server/oss/assets/bootstrap.min.css (Bootstrap v4.5.2, MIT license), gzip-compressed.")
[void]$sb.AppendLine("// Original size $($bytes.Length) bytes, compressed $($data.Length) bytes.")
[void]$sb.AppendLine("#pragma once")
[void]$sb.AppendLine("#include <stddef.h>")
[void]$sb.AppendLine("#include <stdint.h>")
[void]$sb.AppendLine("")
[void]$sb.Append("static const uint8_t bootstrap_css_gz[] = {")
for ($i = 0; $i -lt $data.Length; $i++) {
  if ($i % 24 -eq 0) { [void]$sb.Append("`n  ") }
  [void]$sb.Append(("0x{0:x2}," -f $data[$i]))
}
[void]$sb.AppendLine("`n};")
[void]$sb.AppendLine("static const size_t bootstrap_css_gz_len = sizeof(bootstrap_css_gz);")

New-Item -ItemType Directory -Force (Split-Path $Out) | Out-Null
[IO.File]::WriteAllText($Out, $sb.ToString(), (New-Object Text.UTF8Encoding($false)))
Write-Host "wrote $Out ($($data.Length) bytes gzip from $($bytes.Length) bytes)"
