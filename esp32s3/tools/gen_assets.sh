#!/bin/sh
# Regenerates vrata/src/generated/bootstrap_css.h from the site's Bootstrap CSS.
# POSIX shell equivalent of gen_assets.ps1; the output format is the same.
# Only needed if the CSS is ever replaced - the header is committed.
#
#   ./tools/gen_assets.sh
set -eu

here=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
css=${1:-"$here/../../server/oss/assets/bootstrap.min.css"}
out=${2:-"$here/../vrata/src/generated/bootstrap_css.h"}

[ -f "$css" ] || { echo "gen_assets: no such CSS file: $css" >&2; exit 1; }

tmp=$(mktemp)
trap 'rm -f "$tmp"' EXIT
gzip -9 -n -c "$css" > "$tmp"

{
  echo "// GENERATED by tools/gen_assets.sh (or .ps1) - do not edit."
  echo "// Source: server/oss/assets/bootstrap.min.css (Bootstrap v4.5.2, MIT license), gzip-compressed."
  echo "// Original size $(wc -c < "$css" | tr -d ' ') bytes, compressed $(wc -c < "$tmp" | tr -d ' ') bytes."
  echo "#pragma once"
  echo "#include <stddef.h>"
  echo "#include <stdint.h>"
  echo
  echo "static const uint8_t bootstrap_css_gz[] = {"
  od -An -v -tu1 "$tmp" | tr -s ' ' '\n' | sed '/^$/d' |
    awk 'BEGIN { ORS = "" } { printf "%s0x%02x,", (NR % 24 == 1 ? "\n  " : ""), $1 } END { printf "\n" }'
  echo "};"
  echo "static const size_t bootstrap_css_gz_len = sizeof(bootstrap_css_gz);"
} > "$out"

echo "wrote $out"
